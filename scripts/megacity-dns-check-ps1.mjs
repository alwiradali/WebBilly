#!/usr/bin/env node
/* Writes a PowerShell version of megacity-dns-check.mjs, for checking Walid's
   Cloudflare zone from a Windows machine before the nameservers move.

   It exists because the Node checker cannot do that job from the container this
   project is developed in: every DNS query there is answered by a local
   resolver whatever server you name, so the check silently read public DNS —
   still GoDaddy's zone — and passed. See scripts/lib/dns-raw.mjs.

   The generated script carries the same guard. Before checking anything it asks
   the nameserver about bbc.co.uk, which Cloudflare's nameservers cannot be
   authoritative for; if an answer comes back, something is intercepting DNS on
   that machine too and the run stops rather than reporting a meaningless pass.

     node scripts/megacity-dns-check-ps1.mjs > check-megacity-dns.ps1

   Then on Windows, in PowerShell:
     .\check-megacity-dns.ps1 aaron.ns.cloudflare.com                          */

import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOM = "megacityproperties.co.uk";
const EXPORT = join(ROOT, "docs/megacity-old-site/dns-export.txt");

const rows = [];
for (const line of readFileSync(EXPORT, "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#") || line.startsWith("-") || /^NAME\s+TYPE/.test(line)) continue;
  const m = line.match(/^(\S+)\s+(A|AAAA|CNAME|MX|TXT|SRV|CAA|NS)\s+(\d+)\s+(.+?)\s*$/);
  if (m) rows.push({ name: m[1], type: m[2], value: m[4] });
}
if (!rows.length) throw new Error("no records parsed from " + EXPORT);

const fqdn = (n) => (n === "@" ? DOM : `${n}.${DOM}`);
const doubled = (n) => n.toLowerCase().endsWith("." + DOM);   /* see dns-export.txt */
const isCritical = (r) =>
  ["@ MX", "@ TXT", "autodiscover CNAME", "_dmarc TXT", "_amazonses TXT"].includes(`${r.name} ${r.type}`) ||
  (r.type === "CNAME" && /(^|\.)_domainkey(\.|$)/.test(r.name) && !doubled(r.name));

/* PowerShell single quotes escape by doubling. */
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const lines = [
`<#  Checks megacityproperties.co.uk against the record inventory, asking one`,
`    nameserver directly. Generated by scripts/megacity-dns-check-ps1.mjs from`,
`    docs/megacity-old-site/dns-export.txt — ${rows.length} records. Do not edit by hand.`,
``,
`    Usage:  .\\check-megacity-dns.ps1 aaron.ns.cloudflare.com`,
``,
`    Run it BEFORE the nameservers are changed at GoDaddy. Nothing is live on`,
`    Cloudflare yet, so a failure here costs nothing and catches everything. #>`,
``,
`param([Parameter(Mandatory=$true)][string]$Server)`,
``,
`$ErrorActionPreference = 'SilentlyContinue'`,
`Write-Host ""`,
`Write-Host "Checking ${DOM} against $Server" -ForegroundColor Cyan`,
`Write-Host ""`,
``,
`# A nameserver that only serves its own zones cannot answer for bbc.co.uk.`,
`# If it does, something on this network is answering in its place and every`,
`# result below would be public DNS - which is still the OLD zone.`,
`$foreign = Resolve-DnsName -Name 'bbc.co.uk' -Type NS -Server $Server -DnsOnly -ErrorAction SilentlyContinue`,
`if ($foreign) {`,
`  Write-Host "STOP: $Server answered a query about bbc.co.uk." -ForegroundColor Red`,
`  Write-Host "Something on this network is intercepting DNS, so nothing this script"`,
`  Write-Host "reports would mean anything. Try another network, then run it again."`,
`  exit 2`,
`}`,
``,
`$ok = 0; $bad = 0; $criticalBad = 0`,
``,
`function Check($name, $type, $want, $critical) {`,
`  $r = Resolve-DnsName -Name $name -Type $type -Server $Server -DnsOnly -ErrorAction SilentlyContinue`,
`  $got = @()`,
`  foreach ($x in $r) {`,
`    switch ($type) {`,
`      'A'     { if ($x.IPAddress)     { $got += $x.IPAddress } }`,
`      'CNAME' { if ($x.NameHost)      { $got += $x.NameHost } }`,
`      'MX'    { if ($x.NameExchange)  { $got += "$($x.Preference) $($x.NameExchange)" } }`,
`      'TXT'   { if ($x.Strings)       { $got += ($x.Strings -join '') } }`,
`      'SRV'   { if ($x.NameTarget)    { $got += "$($x.Priority) $($x.Weight) $($x.Port) $($x.NameTarget)" } }`,
`    }`,
`  }`,
`  $norm = { param($v) ($v -replace '\\.$','' -replace '^"','' -replace '"$','' -replace '\\s+',' ').ToLower().Trim() }`,
`  $target = & $norm $want`,
`  $hit = $false`,
`  foreach ($g in $got) { if ((& $norm $g) -eq $target) { $hit = $true } }`,
`  $label = "$name $type".PadRight(62)`,
`  if ($hit) {`,
`    Write-Host "ok   $label" -ForegroundColor Green`,
`    $script:ok++`,
`  } else {`,
`    $script:bad++`,
`    if ($critical) { $script:criticalBad++; Write-Host "STOP $label" -ForegroundColor Red }`,
`    else { Write-Host "MISS $label" -ForegroundColor Yellow }`,
`    Write-Host "       wanted: $want"`,
`    if ($got.Count) { Write-Host "       found : $($got -join ' | ')" } else { Write-Host "       found : nothing at that name" }`,
`  }`,
`}`,
``,
];

for (const r of rows) {
  lines.push(`Check ${q(fqdn(r.name))} ${q(r.type)} ${q(r.value)} $${isCritical(r) ? "true" : "false"}`);
}

lines.push(
``,
`Write-Host ""`,
`if ($criticalBad -gt 0) {`,
`  Write-Host "DNS CHECK: $criticalBad EMAIL RECORD(S) WRONG - do not change the nameservers." -ForegroundColor Red`,
`  Write-Host "Fix these in Cloudflare and run this again. Walid's mailboxes depend on them."`,
`  exit 1`,
`} elseif ($bad -gt 0) {`,
`  Write-Host "DNS CHECK: $bad non-critical record(s) missing. Email is safe; add them when you can." -ForegroundColor Yellow`,
`  exit 1`,
`} else {`,
`  Write-Host "DNS CHECK: ALL $ok PASS - the Cloudflare zone answers exactly like the old one." -ForegroundColor Green`,
`  Write-Host "Safe to change the nameservers at GoDaddy."`,
`  exit 0`,
`}`,
``);

process.stdout.write(lines.join("\r\n"));
