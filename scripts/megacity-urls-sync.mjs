#!/usr/bin/env node
/* Copies the browser-safe part of worker/studio/urls.js (between the
   @browser markers) into templates/megacity-urls.js as a plain script that
   sets window.MCUrls. The Worker and the site's own scripts then agree on
   every link in both modes.
     node scripts/megacity-urls-sync.mjs           (writes the copy)
     node scripts/megacity-urls-sync.mjs --check   (exits 1 when stale) */
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../worker/studio/urls.js", import.meta.url), "utf8");
const m = /\/\* @browser-start \*\/([\s\S]*?)\/\* @browser-end \*\//.exec(src);
if (!m) { console.error("megacity-urls-sync: @browser markers missing in worker/studio/urls.js"); process.exit(1); }

const out = `/* GENERATED by scripts/megacity-urls-sync.mjs from worker/studio/urls.js. Do not edit.
   window.MCUrls: the site's own scripts ask it for links, so one page works
   at /templates/megacity-<slug> on the demo host and at root paths on
   megacityproperties.co.uk. */
(function () {
  "use strict";
${m[1].trim()}
  function browserMode() {
    return location.pathname.indexOf("/templates/") === 0 || DEMO_HOSTS.test(location.hostname) ? "demo" : "root";
  }
  window.MCUrls = {
    mode: browserMode,
    href: function (v) { return rewriteHref(v, browserMode()); },
    page: function (slug, frag) { return pagePath(browserMode(), slug, frag); },
    listing: function (id) { return listingPath(browserMode(), id); },
    studio: function (hash) { return studioPath(browserMode(), hash); },
    pagePrefix: function () { return browserMode() === "root" ? "/" : "/templates/megacity-"; },
    slugOf: function (p) { return slugOfPath(p, browserMode()); },
    ROOT_MAP: ROOT_MAP, LEGACY_LISTINGS: LEGACY_LISTINGS
  };
})();
`;
const dest = new URL("../templates/megacity-urls.js", import.meta.url);
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(dest, "utf8"); } catch {}
  if (cur !== out) { console.error("megacity-urls-sync: templates/megacity-urls.js is stale. Run: node scripts/megacity-urls-sync.mjs"); process.exit(1); }
  console.log("megacity-urls-sync: in sync");
} else {
  writeFileSync(dest, out);
  console.log("megacity-urls-sync: wrote templates/megacity-urls.js");
}
